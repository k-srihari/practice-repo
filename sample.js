export function add(a, b, c) {
  //adding numbers
  return a + b + c
}

export function subtract(a, b) {
  return a - b
}

export function multiply(a, b, c) {
  return a * b * c
}

export function divide(a, b) {
  return a / b
}

export function findRemainder(a, b) {
  return a % b
}

export function call(a) {
  return a
}
